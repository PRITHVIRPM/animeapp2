    fun getAnimeById(id: Int): Anime? = allAnime.find { it.id == id }

    fun getFeaturedSpotlight(): Anime = allAnime.first() // Frieren

    fun getByMood(mood: AnimeMood): List<Anime> {
        return allAnime.filter { it.vibes.contains(mood) }
    }

    fun getByGenre(genre: String): List<Anime> {
        return allAnime.filter { it.genres.any { g -> g.equals(genre, ignoreCase = true) } }
    }

    fun search(query: String): List<Anime> {
        if (query.isBlank()) return allAnime
        val q = query.trim().lowercase()
        return allAnime.filter {
            it.title.lowercase().contains(q) ||
            it.englishTitle.lowercase().contains(q) ||
            it.japaneseTitle.lowercase().contains(q) ||
            it.studio.lowercase().contains(q) ||
            it.genres.any { g -> g.lowercase().contains(q) } ||
            it.tags.any { t -> t.lowercase().contains(q) }
        }
    }

    fun getSimilarAnime(target: Anime): List<Anime> {
        return allAnime
            .filter { it.id != target.id }
            .map { candidate ->
                var score = 0
                val commonGenres = candidate.genres.intersect(target.genres.toSet()).size
                score += commonGenres * 3

                val commonVibes = candidate.vibes.intersect(target.vibes.toSet()).size
                score += commonVibes * 4

                if (candidate.studio.contains(target.studio) || target.studio.contains(candidate.studio)) {
                    score += 2
                }

                if (target.similarTitles.any { candidate.title.contains(it, ignoreCase = true) || it.contains(candidate.title, ignoreCase = true) }) {
                    score += 10
                }

                Pair(candidate, score)
            }
            .sortedByDescending { it.second }
            .take(5)
            .map { it.first }
    }
